# 1. RDKitCheminformaticsNode
# ==============================================================================

def test_rdkit_cheminformatics_node(test_env):
    node = RDKitCheminformaticsNode()
    # Test acetaminophen: CC(=O)Nc1ccc(O)cc1
    smi, mw, logp, hbd = node.run("CC(=O)Nc1ccc(O)cc1")
    assert smi == "CC(=O)Nc1ccc(O)cc1"
    assert round(mw, 1) == 151.1
    assert round(logp, 2) == 1.35
    assert hbd == 2

    # Test aspirin: CC(=O)Oc1ccccc1C(=O)O
    smi, mw, logp, hbd = node.run("CC(=O)Oc1ccccc1C(=O)O")
    assert "C(=O)O" in smi
    assert round(mw, 1) == 180.0
    assert hbd == 1

    # Test file not found error
    with pytest.raises(FileNotFoundError):
        node.run("/nonexistent/file.smi")

    # Test invalid SMILES error
    with pytest.raises(ValueError):
        node.run("INVALID_SMILES_NOT_A_MOL%%%")


