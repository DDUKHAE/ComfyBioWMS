# 2. ProDyDynamicsNode
# ==============================================================================

def test_prody_dynamics_node(test_env):
    node = ProDyDynamicsNode()
    # Missing file check
    with pytest.raises(FileNotFoundError):
        node.run("/nonexistent/missing.pdb")

    # ANM Model
    res_json, num_modes = node.run(str(test_env["pdb"]), model_type="ANM", num_modes=3)
    assert num_modes == 3
    data = json.loads(res_json)
    assert data["model"] == "ANM"
    assert data["num_atoms"] == 3  # 3 CA atoms in sample pdb
    assert len(data["eigenvalues"]) == 3
    assert all(ev > 0 for ev in data["eigenvalues"])

    # GNM Model
    res_json_gnm, num_modes_gnm = node.run(str(test_env["pdb"]), model_type="GNM", num_modes=2)
    assert num_modes_gnm == 2
    data_gnm = json.loads(res_json_gnm)
    assert data_gnm["model"] == "GNM"
    assert len(data_gnm["eigenvalues"]) == 2


